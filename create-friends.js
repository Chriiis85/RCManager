const createTableSql = `
CREATE TABLE IF NOT EXISTS public.friends (
  id bigint generated by default as identity primary key,
  user_id bigint not null,
  friend_id bigint not null,
  status text not null default 'PENDING',
  created_at timestamp with time zone default timezone('utc'::text, now()) not null,
  unique(user_id, friend_id)
);

ALTER TABLE public.friends ENABLE ROW LEVEL SECURITY;

-- Policy for reading: users can read if they are either user_id or friend_id
DROP POLICY IF EXISTS "Users can read their own friendships" ON public.friends;
CREATE POLICY "Users can read their own friendships" 
ON public.friends FOR SELECT 
USING (true); -- En este proyecto el auth es manual/JWT custom, por lo que RLS lo usaremos abierto para lectura via anon, o controlaremos vía frontend

-- Policy for inserting: anyone can insert for now (since auth is custom and verified in backend API usually, but here we insert via Supabase client directly)
-- Wait, we need to allow INSERT and UPDATE for the anon key since the frontend will call it.
DROP POLICY IF EXISTS "Anon can manage friendships" ON public.friends;
CREATE POLICY "Anon can manage friendships" 
ON public.friends FOR ALL 
USING (true) WITH CHECK (true);
`;

async function main() {
  const client = new Client({ connectionString });
  try {
    await client.connect();
    console.log('Connected to DB');
    await client.query(createTableSql);
    console.log('Table public.friends created and RLS configured.');
  } catch (err) {
    console.error('Error creating table:', err);
  } finally {
    await client.end();
  }
}

main();
